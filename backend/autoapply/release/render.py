"""The three things made from the release data: CHANGELOG.md, the app's releases.json, a release's GitHub notes.

Same inputs and the same generator give the same bytes: no clock, no random, no order that is not written down
(releases newest first by version; changes in their manifest's order; JSON keys sorted).
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from . import versions
from .checks import TYPE_ORDER
from .model import Fragment, Manifest, Repo

GENERATED_NOTE = ("Generated by `python scripts/release.py generate` from changes/. "
                  "Do not edit by hand - see docs/release-workflow.md.")
CHANGELOG = "CHANGELOG.md"
APP_DATA = "backend/autoapply/releases.json"
DEFAULT_REPO = "Liam-Frost/AutoApply"
SECTIONS = {"added": "Added", "changed": "Changed", "deprecated": "Deprecated", "removed": "Removed",
            "fixed": "Fixed", "security": "Security"}
LANGS = ("en", "zh", "fr")


def github_repo(root: Path) -> str:
    """owner/name of the GitHub repository the releases are published in: pyproject's [project.urls] Releases."""
    try:
        import tomllib

        urls = tomllib.loads((Path(root) / "pyproject.toml").read_text(encoding="utf-8")).get("project", {}).get("urls", {})
    except (OSError, ValueError):
        urls = {}
    for key in ("Releases", "Homepage", "Repository", "Source"):
        m = re.match(r"^https://github\.com/([\w.-]+/[\w.-]+?)(?:\.git)?(?:/.*)?$", str(urls.get(key, "")))
        if m:
            return m.group(1)
    return DEFAULT_REPO


def release_url(repo_name: str, version: str) -> str:
    return f"https://github.com/{repo_name}/releases/tag/v{version}"


def _words(d: dict[str, str]) -> dict[str, str]:
    return {k: d[k] for k in LANGS if isinstance(d.get(k), str) and d[k]}


def change_entry(f: Fragment) -> dict[str, Any]:
    return {"id": f.id, "type": f.type, "scope": f.scope, "summary": _words(f.summary), "details": f.details,
            "highlight": f.highlight}


def released(repo: Repo) -> list[tuple[Manifest, list[Fragment]]]:
    """Every release, newest first, with its fragments in manifest order (a fragment that cannot be read is left out:
    `validate` says so, and `generate` does not run with errors)."""
    out = []
    for m in repo.manifests:
        if not versions.valid(m.version):
            continue
        out.append((m, [repo.fragments[fid] for fid in dict.fromkeys(m.ids) if fid in repo.fragments]))
    return out


def release_entry(m: Manifest, frags: list[Fragment], repo_name: str) -> dict[str, Any]:
    return {"version": m.version, "date": m.date, "title": _words(m.title), "intro": m.intro.strip(),
            "known_limits": [x.strip() for x in m.known_limits], "url": release_url(repo_name, m.version),
            "changes": [change_entry(f) for f in frags]}


def app_data(repo: Repo) -> dict[str, Any]:
    name = github_repo(repo.root)
    return {"_generated": GENERATED_NOTE, "schema": 1, "repo": name,
            "releases": [release_entry(m, frags, name) for m, frags in released(repo)]}


def app_data_text(repo: Repo) -> str:
    return dumps_app_data(app_data(repo))


def dumps_app_data(data: dict[str, Any]) -> str:
    return json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True) + "\n"


def pending_changes(repo: Repo, frags: list[Fragment] | None = None) -> list[dict[str, Any]]:
    return [change_entry(f) for f in (repo.pending if frags is None else frags)]


# --- Markdown ------------------------------------------------------------------------------------------------------------
def _indent(text: str, by: str = "  ") -> str:
    return "\n".join(by + line if line.strip() else "" for line in text.split("\n"))


def _item(summary: str, details: str) -> str:
    """One change: `- **summary**`, its details below, indented so that their lists nest under it."""
    head = f"- **{summary}**"
    return head + ("\n\n" + _indent(details) if details else "")


def body(m: Manifest, frags: list[Fragment]) -> str:
    """A release's notes under its heading: the intro, a section per type, the known limits."""
    parts: list[str] = []
    if m.intro.strip():
        parts.append(m.intro.strip())
    for t in TYPE_ORDER:
        items = [f for f in frags if f.type == t]
        if not items:
            continue
        loose = any(f.details for f in items)          # a list with paragraphs in it: an empty line between items
        sep = "\n\n" if loose else "\n"
        parts.append(f"### {SECTIONS[t]}\n\n" + sep.join(_item(f.summary.get("en", f.id), f.details) for f in items))
    limits = [x.strip() for x in m.known_limits if x.strip()]
    if limits:
        loose = any("\n" in x for x in limits)
        parts.append("### Known limits\n\n" + ("\n\n" if loose else "\n").join("- " + _indent(x).lstrip() for x in limits))
    return "\n\n".join(parts) + "\n"


def changelog(repo: Repo) -> str:
    name = github_repo(repo.root)
    rel = released(repo)
    out = ["# Changelog", "", f"<!-- {GENERATED_NOTE} -->", "",
           "All notable changes to AutoApply, newest first. Versions follow [Semantic Versioning](https://semver.org/); "
           "changes not released yet are pending fragments in `changes/fragments/`.", ""]
    for m, frags in rel:
        out += [f"## [{m.version}] - {m.date}", "", body(m, frags).rstrip("\n"), ""]
    if rel:
        out += [f"[{m.version}]: {release_url(name, m.version)}" for m, _ in rel] + [""]
    return "\n".join(out)


def notes(repo: Repo, version: str) -> str:
    """A release's GitHub notes: what CHANGELOG.md says under its heading. KeyError when there is no such release."""
    m = repo.manifest(version)
    if m is None:
        raise KeyError(version)
    return body(m, [repo.fragments[fid] for fid in dict.fromkeys(m.ids) if fid in repo.fragments])
